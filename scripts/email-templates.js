// Builds the Supabase Auth email templates from the app's locale files (A-01.1), so email
// copy is translated like every other string (CLAUDE.md, localization rules).
//
//   node scripts/email-templates.js --check   fail if a template or subject is out of date (CI)
//   node scripts/email-templates.js --write   regenerate supabase/templates after a copy change
//
// Supabase sends one template per email type, so the template picks the copy with Go
// template conditions on the locale saved in the user's metadata at sign-up. Locales whose
// copy is the same as en-US share its branch.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const LOCALES = ['en-US', 'en-GB', 'en-AU'];
const DEFAULT_LOCALE = 'en-US';
const CONFIG = path.join(root, 'supabase/config.toml');
const TEMPLATE = path.join(root, 'supabase/templates/sign-in-code.html');
// Brand colors from the light theme in src/constants/theme.ts (email clients have no dark
// theme we can rely on).
const COLORS = { background: '#FAF7F2', text: '#2B2A28', primary: '#3F6B4F' };

function loadCopy(locale) {
  const read = (l) =>
    JSON.parse(fs.readFileSync(path.join(root, `src/i18n/locales/${l}.json`), 'utf8'));
  const fallback = read(DEFAULT_LOCALE).email?.signInCode ?? {};
  // Regional files only hold what differs from en-US, like i18next's fallback.
  const own = locale === DEFAULT_LOCALE ? {} : (read(locale).email?.signInCode ?? {});
  return { ...fallback, ...own };
}

function escapeHtml(text) {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Fills i18next-style {{name}} placeholders, so none can reach the Go template. */
function interpolate(text, values) {
  const result = text.replace(/\{\{\s*(\w+)\s*\}\}/g, (match, name) => {
    if (!(name in values)) throw new Error(`No value for {{${name}}} in "${text}"`);
    return String(values[name]);
  });
  if (result.includes('{{') || result.includes('}}')) {
    throw new Error(`Unexpected braces in "${text}"`);
  }
  return result;
}

const KEYS = ['subject', 'heading', 'intro', 'expiry', 'linkIntro', 'linkLabel', 'ignore'];

/** The email body for one locale. `{{ .Token }}` and `{{ .ConfirmationURL }}` are Supabase's. */
function renderBody(copy, { minutes }) {
  for (const key of KEYS) {
    if (typeof copy[key] !== 'string' || copy[key].trim() === '') {
      throw new Error(`Missing email.signInCode.${key}`);
    }
  }
  const text = (key) => escapeHtml(interpolate(copy[key], { minutes }));
  return [
    `<h1 style="font-size:22px;margin:0 0 16px">${text('heading')}</h1>`,
    `<p style="margin:0 0 12px">${text('intro')}</p>`,
    `<p style="font-size:32px;font-weight:700;letter-spacing:8px;margin:0 0 12px;font-family:Menlo,Consolas,monospace">{{ .Token }}</p>`,
    `<p style="margin:0 0 24px">${text('expiry')}</p>`,
    `<p style="margin:0 0 8px">${text('linkIntro')}</p>`,
    `<p style="margin:0 0 24px"><a href="{{ .ConfirmationURL }}" style="color:${COLORS.primary}">${text('linkLabel')}</a></p>`,
    `<p style="margin:0;font-size:14px">${text('ignore')}</p>`,
  ].join('\n');
}

/** The whole template, with a branch for each locale whose copy differs from en-US. */
function renderTemplate(copies, { minutes }) {
  const fallback = renderBody(copies[DEFAULT_LOCALE], { minutes });
  const branches = [];
  for (const locale of LOCALES) {
    if (locale === DEFAULT_LOCALE) continue;
    const body = renderBody(copies[locale], { minutes });
    if (body !== fallback) branches.push({ locale, body });
  }
  let content = fallback;
  if (branches.length > 0) {
    // printf turns a missing locale into "<nil>" rather than failing the comparison.
    const parts = branches.map(
      ({ locale, body }, i) =>
        `{{ ${i === 0 ? 'if' : 'else if'} eq (printf "%v" .Data.locale) "${locale}" }}\n${body}`,
    );
    content = `${parts.join('\n')}\n{{ else }}\n${fallback}\n{{ end }}`;
  }
  return [
    '<!-- Generated by scripts/email-templates.js from src/i18n/locales. Do not edit. -->',
    '<!doctype html>',
    `<html><body style="margin:0;padding:24px;background:${COLORS.background};color:${COLORS.text};font-family:-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;font-size:16px;line-height:1.5">`,
    content,
    '</body></html>',
    '',
  ].join('\n');
}

/** Reads the code lifetime and the email subjects from supabase/config.toml. */
function readConfig(toml) {
  const expiry = toml.match(/^\s*otp_expiry\s*=\s*(\d+)/m);
  if (!expiry) throw new Error('otp_expiry not found in supabase/config.toml');
  const subjects = [
    ...toml.matchAll(/\[auth\.email\.template\.(\w+)\]\s*\nsubject\s*=\s*"([^"]*)"/g),
  ].map((m) => ({ type: m[1], subject: m[2] }));
  return { minutes: Number(expiry[1]) / 60, subjects };
}

function main(mode) {
  const config = readConfig(fs.readFileSync(CONFIG, 'utf8'));
  const copies = Object.fromEntries(LOCALES.map((l) => [l, loadCopy(l)]));
  const expected = renderTemplate(copies, config);
  const problems = [];
  const subject = copies[DEFAULT_LOCALE].subject;
  for (const type of ['confirmation', 'magic_link']) {
    const found = config.subjects.find((s) => s.type === type);
    if (!found) problems.push(`[auth.email.template.${type}] is missing from config.toml`);
    else if (found.subject !== subject) {
      problems.push(`[auth.email.template.${type}] subject should be "${subject}"`);
    }
  }
  if (mode === '--write') {
    fs.mkdirSync(path.dirname(TEMPLATE), { recursive: true });
    fs.writeFileSync(TEMPLATE, expected);
  } else {
    const actual = fs.existsSync(TEMPLATE) ? fs.readFileSync(TEMPLATE, 'utf8') : '';
    if (actual !== expected) {
      problems.push(`${path.relative(root, TEMPLATE)} is out of date`);
    }
  }
  if (problems.length > 0) {
    for (const p of problems) console.error(p);
    console.error('Run `pnpm run email:templates` and update the subjects in config.toml.');
    process.exit(1);
  }
  console.log(mode === '--write' ? 'Email templates written.' : 'Email templates are current.');
}

if (require.main === module) {
  const mode = process.argv[2];
  if (mode !== '--check' && mode !== '--write') {
    console.error('Usage: node scripts/email-templates.js --check | --write');
    process.exit(2);
  }
  main(mode);
}

module.exports = { escapeHtml, interpolate, readConfig, renderBody, renderTemplate };
