// Validates the ingredient catalog (supabase/catalog/ingredients.json) and turns it into a
// seed migration (R-01.2). The JSON is the source of truth; the migration is generated.
//
//   node scripts/catalog-seed.js --check            validate, and fail if the newest seed
//                                                   migration doesn't match the JSON (CI)
//   node scripts/catalog-seed.js --new [timestamp]  write a new seed migration after a change
//
// A migration that has been applied is never edited, so every catalog change gets a new
// seed migration. Each one upserts every row and soft-deletes catalog rows no longer in
// the JSON, so the newest one always describes the whole catalog.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const migrations = path.join(root, 'supabase/migrations');
const SEED_SUFFIX = '_ingredient_catalog_seed.sql';
const LOCALES = ['en-US', 'en-GB', 'en-AU'];
const DIMENSIONS = ['mass', 'volume', 'count'];

// Section IDs and allergen codes come from the app's own list, which the schema also checks.
const idsSource = fs.readFileSync(
  path.join(root, 'src/features/ingredients/catalog-ids.ts'),
  'utf8',
);
const SECTIONS = new Set(idsSource.match(/'section\.[a-z0-9_]+'/g).map((s) => s.slice(1, -1)));
const ALLERGENS = new Set(idsSource.match(/'allergen\.[a-z0-9_]+'/g).map((s) => s.slice(1, -1)));

/** The same normalization the on-device matcher uses: case, accents and punctuation don't count. */
function normalize(text) {
  return text
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/['\u2019]/g, '')
    .replace(/[^a-z0-9%]+/g, ' ')
    .trim();
}

function validate(catalog) {
  const errors = [];
  const ids = new Set();
  const owners = Object.fromEntries(LOCALES.map((l) => [l, new Map()]));
  for (const item of catalog.ingredients) {
    const where = item.id;
    if (!/^ingredient\.[a-z0-9_]+$/.test(item.id)) errors.push(`${where}: bad ID`);
    if (ids.has(item.id)) errors.push(`${where}: duplicate ID`);
    ids.add(item.id);
    if (!SECTIONS.has(item.section)) errors.push(`${where}: unknown section ${item.section}`);
    if (!DIMENSIONS.includes(item.dimension)) errors.push(`${where}: bad dimension`);
    if (item.density !== null && !(item.density > 0)) errors.push(`${where}: bad density`);
    if (item.density !== null && item.dimension === 'count') {
      errors.push(`${where}: a count ingredient has no density`);
    }
    for (const code of item.allergens) {
      if (!ALLERGENS.has(code)) errors.push(`${where}: unknown allergen ${code}`);
    }
    if (typeof item.staple !== 'boolean') errors.push(`${where}: staple must be true or false`);
    for (const locale of LOCALES) {
      const names = item.names[locale];
      if (!names || !names.name) {
        errors.push(`${where}: no ${locale} name`);
        continue;
      }
      const terms = [names.name, names.plural, ...names.synonyms].filter(Boolean);
      if (terms.some((t) => t.length > 100))
        errors.push(`${where}: ${locale} name over 100 characters`);
      if (names.synonyms.length > 20) errors.push(`${where}: ${locale} has over 20 synonyms`);
      // Two ingredients answering to the same word would make matching guess (R-ING-6).
      for (const term of terms) {
        const key = normalize(term);
        const owner = owners[locale].get(key);
        if (owner && owner !== item.id)
          errors.push(`${locale} "${term}" names ${owner} and ${item.id}`);
        owners[locale].set(key, item.id);
      }
    }
    for (const key of Object.keys(item.names)) {
      if (!LOCALES.includes(key)) errors.push(`${where}: unknown locale ${key}`);
    }
  }
  if (!catalog.ingredients.some((i) => i.staple)) errors.push('no default staples (FR-PAN-1)');
  return errors;
}

const literal = (value) => (value === null ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const textArray = (values) =>
  values.length ? `array[${values.map(literal).join(', ')}]` : `'{}'::text[]`;

function toSql(catalog) {
  const rows = catalog.ingredients;
  const ingredientValues = rows.map(
    (i) =>
      `  (${literal(i.id)}, ${literal(i.dimension)}, ${i.density ?? 'null'}, ${literal(i.section)}, ` +
      `${textArray(i.allergens)}, ${i.staple})`,
  );
  const nameValues = rows.flatMap((i) =>
    LOCALES.map((locale) => {
      const n = i.names[locale];
      return `  (${literal(i.id)}, ${literal(locale)}, ${literal(n.name)}, ${literal(n.plural ?? null)}, ${textArray(n.synonyms)})`;
    }),
  );
  return `-- R-01.2: the ingredient catalog (${rows.length} ingredients in ${LOCALES.join(', ')}).
-- Generated by scripts/catalog-seed.js from supabase/catalog/ingredients.json. Don't edit:
-- change the JSON and generate a new migration.

insert into public.ingredients
  (id, default_dimension, density_g_per_ml, section_id, allergen_codes, is_default_staple)
values
${ingredientValues.join(',\n')}
on conflict (id) do update set
  default_dimension = excluded.default_dimension,
  density_g_per_ml = excluded.density_g_per_ml,
  section_id = excluded.section_id,
  allergen_codes = excluded.allergen_codes,
  is_default_staple = excluded.is_default_staple,
  deleted_at = null;

insert into public.ingredient_names (ingredient_id, locale, name, plural, synonyms)
values
${nameValues.join(',\n')}
on conflict (ingredient_id, locale) do update set
  name = excluded.name,
  plural = excluded.plural,
  synonyms = excluded.synonyms,
  deleted_at = null;

-- Catalog items dropped from the JSON are soft-deleted, so recipes that use them keep working.
update public.ingredients set deleted_at = now()
where household_id is null and deleted_at is null and id <> all (${textArray(rows.map((i) => i.id))});
`;
}

function newestSeed() {
  const files = fs
    .readdirSync(migrations)
    .filter((f) => f.endsWith(SEED_SUFFIX))
    .sort();
  return files.length ? path.join(migrations, files[files.length - 1]) : null;
}

function main(args) {
  const catalog = JSON.parse(
    fs.readFileSync(path.join(root, 'supabase/catalog/ingredients.json'), 'utf8'),
  );
  const errors = validate(catalog);
  if (errors.length) {
    console.error(`The ingredient catalog has ${errors.length} problem(s):\n${errors.join('\n')}`);
    process.exit(1);
  }
  const sql = toSql(catalog);
  if (args[0] === '--check') {
    const seed = newestSeed();
    assert.ok(seed, 'no seed migration found: run node scripts/catalog-seed.js --new');
    if (fs.readFileSync(seed, 'utf8') !== sql) {
      console.error(
        `${path.relative(root, seed)} doesn't match supabase/catalog/ingredients.json.\n` +
          'Generate a new migration with: node scripts/catalog-seed.js --new',
      );
      process.exit(1);
    }
    console.log(`Ingredient catalog OK: ${catalog.ingredients.length} ingredients.`);
  } else if (args[0] === '--new') {
    const stamp = args[1] ?? new Date().toISOString().replace(/\D/g, '').slice(0, 14);
    assert.match(stamp, /^\d{14}$/, 'the timestamp must be 14 digits, like 20261108140000');
    const file = path.join(migrations, `${stamp}${SEED_SUFFIX}`);
    fs.writeFileSync(file, sql);
    console.log(`Wrote ${path.relative(root, file)}`);
  } else {
    console.error('Usage: node scripts/catalog-seed.js --check | --new [timestamp]');
    process.exit(1);
  }
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { normalize, validate, toSql };
